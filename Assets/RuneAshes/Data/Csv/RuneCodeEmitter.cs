using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace RuneAshes.Data
{
    /// <summary>
    /// 把符文列表输出为 C# 常量表。输出是确定性的（params 按 key 排序），便于 diff。
    /// </summary>
    public static class RuneCodeEmitter
    {
        public static string Emit(IReadOnlyList<RuneDef> runes)
        {
            if (runes == null)
            {
                throw new ArgumentNullException("runes");
            }

            var sb = new StringBuilder(8192);
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//   Generated by Rune Ashes/Config/Generate Rune Table from rune.csv.");
            sb.AppendLine("//   Do not edit by hand.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("namespace RuneAshes.Data");
            sb.AppendLine("{");
            sb.AppendLine("    public static class RuneTableData");
            sb.AppendLine("    {");
            sb.AppendLine("        public static readonly RuneDef[] All = new RuneDef[]");
            sb.AppendLine("        {");

            for (var i = 0; i < runes.Count; i++)
            {
                var rune = runes[i];
                sb.Append("            RuneDef.Create(");
                sb.Append(Str(rune.Id)).Append(", ");
                sb.Append(Str(rune.Name)).Append(", ");
                sb.Append("RuneCategory.").Append(rune.Category.ToString()).Append(", ");
                sb.Append(rune.EnergyCost.ToString(CultureInfo.InvariantCulture)).Append(", ");
                sb.Append(Float(rune.BaseValue)).Append(", ");
                sb.Append(rune.MaxLevel.ToString(CultureInfo.InvariantCulture)).Append(", ");
                sb.Append(Str(rune.Description)).Append(", ");

                sb.Append(StrArray(rune.Tags)).Append(", ");

                var keys = new List<string>(rune.Params.Keys);
                keys.Sort(StringComparer.Ordinal);
                var values = new List<string>(keys.Count);
                for (var k = 0; k < keys.Count; k++)
                {
                    values.Add(rune.Params[keys[k]]);
                }

                sb.Append(StrArray(keys)).Append(", ");
                sb.Append(StrArray(values)).Append("),");
                sb.AppendLine();
            }

            sb.AppendLine("        };");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static string StrArray(IReadOnlyList<string> values)
        {
            if (values == null || values.Count == 0)
            {
                return "new string[0]";
            }

            var sb = new StringBuilder();
            sb.Append("new[] { ");
            for (var i = 0; i < values.Count; i++)
            {
                if (i > 0)
                {
                    sb.Append(", ");
                }

                sb.Append(Str(values[i]));
            }

            sb.Append(" }");
            return sb.ToString();
        }

        private static string Float(float value)
        {
            if (float.IsNaN(value) || float.IsInfinity(value))
            {
                throw new ArgumentException("Non-finite float in rune table: " + value);
            }

            return value.ToString("0.0####", CultureInfo.InvariantCulture) + "f";
        }

        private static string Str(string value)
        {
            if (value == null)
            {
                return "\"\"";
            }

            var sb = new StringBuilder(value.Length + 8);
            sb.Append('"');
            foreach (var c in value)
            {
                switch (c)
                {
                    case '\\':
                        sb.Append("\\\\");
                        break;
                    case '"':
                        sb.Append("\\\"");
                        break;
                    case '\n':
                        sb.Append("\\n");
                        break;
                    case '\r':
                        sb.Append("\\r");
                        break;
                    case '\t':
                        sb.Append("\\t");
                        break;
                    default:
                        sb.Append(c);
                        break;
                }
            }

            sb.Append('"');
            return sb.ToString();
        }
    }
}
